def source_pool_cards(
    pool: str, *, unlocked_epochs: Iterable[str] | None = None,
    multiplayer: bool = False, for_combat_generation: bool = False,
) -> tuple[str, ...]:
    """Preserve the C# registry order while applying its explicit predicates."""
    epochs = None if unlocked_epochs is None else {str(e).upper() for e in unlocked_epochs}
    return tuple(card for card in SOURCE_CARD_POOLS.get(pool.lower(), ())
                 if (epochs is None or card not in SOURCE_CARD_UNLOCK_EPOCHS
                     or SOURCE_CARD_UNLOCK_EPOCHS[card] in epochs)
                 and card not in (SINGLEPLAYER_ONLY if multiplayer else MULTIPLAYER_ONLY)
                 and (not for_combat_generation or card not in COMBAT_GENERATION_EXCLUDED))
