def test_startup_moves_and_repeating_attacks_follow_source_machine(monster_id, expected):
    state = _fight((monster_id,))
    observed = [state.combat.monsters[0].move_id]
    for _ in range(2):
        state = _end(state)
        observed.append(state.combat.monsters[0].move_id)
    assert observed == expected


@pytest.mark.parametrize("ascension,block,strength", [(0, 10, 3), (8, 10, 3), (9, 15, 4)])
def test_stock_two_replacements_then_victory_and_boot_up_scaling(ascension, block, strength):
    # Axebot.cs + StockPower.cs: 2 -> 1 -> 0, each replacement is a new model.
    state = _fight(effects={"damage": 10000}, ascension=ascension)
    assert state.combat.monsters[0].move_id == "HAMMER_UPPERCUT"
    assert state.combat.monsters[0].statuses["stock"] == 2
    for remaining in (1, 0):
        state = _play(state)
        assert state.phase == RunPhase.COMBAT
        child = state.combat.monsters[-1]
        assert child.statuses.get("stock", 0) == remaining
        assert child.move_id == "BOOT_UP"
        assert child.metadata["slot_index"] == 0
        # Stable does not include beta v0.111.0's cumulative +10 Max HP.
        assert child.max_hp <= (86 if ascension >= 8 else 78)
        assert child.hp == child.max_hp
        restored = load_state(serialize(state))
        assert serialize(_end(restored)) == serialize(_end(state))
        state = _end(state)
        child = state.combat.monsters[-1]
        assert child.block == block
        assert child.statuses["strength"] == strength * (2 - remaining)
        assert child.move_id == "HAMMER_UPPERCUT"
    state = _play(state)
    assert state.phase == RunPhase.REWARD


@pytest.mark.parametrize("target,effects,loss", [
    ("enemy", {"sequence": [{"damage": 5}] * 3}, 0),
    ("all_enemies", {"sequence": [{"all_damage": 5}] * 3}, 10),
    ("none", {"repeat_damage": {"basis": "energy_spent", "extra_hits": 3,
                                "amount": 5, "target": "a random enemy"}}, 10),
])
def test_replacement_identity_during_targeted_aoe_and_random_multihit(target, effects, loss):
    state = _play(_weaken(_fight(target=target, effects=effects)))
    assert state.phase == RunPhase.COMBAT
    child = state.combat.monsters[-1]
    assert child.hp == child.max_hp - loss
    assert child.statuses["stock"] == 1


