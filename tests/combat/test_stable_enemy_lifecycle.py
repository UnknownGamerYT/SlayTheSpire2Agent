def test_fabricator_builds_defensive_and_aggressive_bots_then_alternates_aggro():
    state = _fight(("FABRICATOR",))
    monster = state.combat.monsters[0].model_copy(update={"move_id": "FABRICATE"})
    state = state.model_copy(update={"combat": state.combat.model_copy(update={
        "monsters": (monster,),
    })})
    state = _end(state)
    defense, aggression = state.combat.monsters[1:]
    assert defense.metadata["source_monster_id"] in {"GUARDBOT", "NOISEBOT"}
    assert aggression.metadata["source_monster_id"] in {"ZAPBOT", "STABBOT"}
    assert defense.statuses["minion"] == aggression.statuses["minion"] == 1
    assert defense.block == aggression.block == 0  # Summons wait for their first turn.
    monsters = list(state.combat.monsters)
    monsters[0] = monsters[0].model_copy(update={"move_id": "FABRICATING_STRIKE"})
    state = state.model_copy(update={"combat": state.combat.model_copy(update={
        "monsters": tuple(monsters),
    })})
    state = _end(load_state(serialize(state)))
    assert state.combat.monsters[-1].metadata["source_monster_id"] in {"ZAPBOT", "STABBOT"} - {
        aggression.metadata["source_monster_id"],
    }
