CACHE = Path(__file__).resolve().parents[2] / "data/cache/eng/monsters.json"
HP_CONTRACTS = json.loads((Path(__file__).resolve().parents[1]
                          / "fixtures/stable_enemy_hp_contracts.json").read_text())["monsters"]


def _fight(ids=("AXEBOT",), *, effects=None, target="enemy", ascension=0):
    rows = json.loads(CACHE.read_text())
    state = new_run(seed=222, character_id="TEST", ascension=ascension, source_data={
        "monsters": rows,
        "encounters": ({"id": "FIXTURE", "monsters": [{"id": i} for i in ids]},),
        "combat_encounter_id": "FIXTURE",
        "deck": [{"card_id": "fixture", "type": "attack", "target": target, "cost": 0,
                  "effects": effects or {"damage": 1}, "copies": 10}],
        "player": {"hp": 10000, "max_hp": 10000},
    })
    start = MapNodeState(node_id="s", act=1, floor=0, lane=0, kind=RoomKind.START)
    fight = MapNodeState(node_id="f", act=1, floor=1, lane=0, kind=RoomKind.MONSTER)
    state = state.model_copy(update={
        "phase": RunPhase.MAP,
        "map": MapState(nodes=(start, fight), edges=(MapEdgeState(from_id="s", to_id="f"),),
                        current_node_id="s", completed_node_ids=("s",)),
    })
    return step(state, next(a for a in legal_actions(state) if a.type == "choose_node"))


def _play(state, target_id=None):
    return step(state, next(a for a in legal_actions(state) if a.type == "play_card"
                            and (target_id is None or a.target_id == target_id)))


def _end(state):
    return step(state, next(a for a in legal_actions(state) if a.type == "end_turn"))


def _weaken(state, index=0, **updates):
    monsters = list(state.combat.monsters)
    monsters[index] = monsters[index].model_copy(update={"hp": 1, **updates})
    return state.model_copy(update={"combat": state.combat.model_copy(update={
        "monsters": tuple(monsters),
    })})


@pytest.mark.parametrize("kind", ["Normal", "Elite", "Boss"])
@pytest.mark.parametrize("ascension", range(11))
def test_all_enemy_kinds_use_tough_eight_deadly_nine(kind, ascension):
    # AscensionLevel.cs: ToughEnemies=8, DeadlyEnemies=9, regardless of room.
    monster = build_monster_definitions([{
        "id": "FIXTURE", "type": kind, "min_hp": 10, "max_hp": 12,
        "min_hp_ascension": 20, "max_hp_ascension": 22,
        "moves": [{"id": "HIT", "damage": {"normal": 3, "ascension": 7}}],
    }])["FIXTURE"]
    assert monster_hp_range(monster, ascension_level=ascension) == (
        (20, 22) if ascension >= 8 else (10, 12)
    )
    assert monster_move_damage(monster, monster.moves[0], ascension_level=ascension) == (
        7 if ascension >= 9 else 3
    )


@pytest.mark.parametrize("contract", HP_CONTRACTS, ids=lambda row: row["monster_id"])
def test_all_registered_monster_hp_contracts(contract):
    definition = build_monster_definitions(json.loads(CACHE.read_text()))[contract["monster_id"]]
